"""Bundle assets/icons/*.svg into src/icons.js.

Browsers block reading local files from file:// pages, so the icons ship
as strings. Run again after adding or changing an icon:
    python3 tools/build_icons.py
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
icons = {}
for path in sorted(glob.glob(os.path.join(ROOT, "assets", "icons", "*.svg"))):
    svg = open(path).read()
    svg = svg.replace('<path d="M0 0h512v512H0z"/>', "")  # drop black background
    svg = re.sub(r'fill="#fff"', 'fill="currentColor"', svg)
    svg = svg.replace("<svg ", '<svg width="512" height="512" ', 1)
    icons[os.path.splitext(os.path.basename(path))[0]] = svg

out = "// Generated by tools/build_icons.py from assets/icons. Do not edit.\n"
out += "(function (g) {\n  const FU = (g.FU = g.FU || {});\n  FU.ICON_SVG = "
out += json.dumps(icons, indent=2) + ";\n"
out += '})(typeof window !== "undefined" ? window : globalThis);\n'
open(os.path.join(ROOT, "src", "icons.js"), "w").write(out)
print(len(icons), "icons bundled")
